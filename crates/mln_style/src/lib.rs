//! Ports the MapLibre Native style module (`src/mln/style`,
//! `include/mln/style`): `Style` / `Style::Impl`, the parser, layers with the
//! Impl idiom, the property system and the typed `style/conversion`
//! converters. Also holds cut-point copies of a few renderer/map headers that
//! style/properties.hpp includes (`renderer`, `map`) and the style half of
//! the layer manager (`layermanager`). The C++ modules include each other in
//! one cycle, which crates can't; these cut points are where the port breaks
//! it.
//!
//! Path guide (C++ -> Rust):
//! - `style::Style`, `Style::Impl` -> `style::Style`, `style::Impl`
//! - `Layer`, `Layer::Impl` -> `layer::Layer` (trait), `layer::Impl` (trait) +
//!   `layer::ImplBase` (its data members); `Immutable<Layer::Impl>` ->
//!   `Immutable<dyn layer::Impl>`
//! - `BackgroundLayer`, `BackgroundLayer::Impl` ->
//!   `layers::background_layer::{BackgroundLayer, Impl}`
//! - `BackgroundPaintProperties::Unevaluated` etc. ->
//!   `layers::BackgroundPaintProperties::{Transitionable, Unevaluated, PossiblyEvaluated, Evaluated}`
//! - every other layer type likewise (`layers::CircleLayer`,
//!   `layers::circle_layer::Impl`, `layers::CirclePaintProperties`,
//!   `layers::CircleLayoutProperties`, ...): `layers/<type>_layer.rs` and
//!   `layers/<type>_layer_properties.rs` (and `light.rs`) are generated by
//!   //tools/style-codegen from the style spec, as C++ generates theirs.

